/**
 * הזמנה להשאיר ביקורת בגוגל - רק ללקוח שאמר במפורש שהיה ושנהנה.
 *
 * הדרישה של בעל העסק (17.9): "אם יש לך ספק אם הם היו ונהנו אז מבחינתי לא
 * לשלוח, רק אם אתה בטוח ב-100%". לכן ההחלטה כאן היא **בקוד ולא במודל**,
 * והיא מוטה בכוונה לכיוון של לא לשלוח:
 *
 *   - חייבים **שני** אותות נפרדים: אמירה מפורשת שהיו כאן בעבר, **וגם** שבח מפורש.
 *   - כל רמז לשלילה, הסתייגות או שאלה פתוחה - מבטל.
 *   - ספק לשוני נפוץ (למשל "הייתי רוצה להזמין") מבוטל מראש.
 *
 * העלות של טעות איננה סימטרית: לקוח שלא קיבל הזמנה לביקורת לא הפסיד כלום,
 * ולקוח שהתלונן וקיבל בקשה לביקורת זו פגיעה אמיתית. מכאן כל האיזון של הקובץ.
 */

/** גבול מילה בעברית, כולל אות שימוש מחוברת (ראה day-context.ts) */
const B = "(^|[^\\p{L}])[לבהוכשמ]?";
const A = "(?![\\p{L}])";
const rx = (body: string) => new RegExp(`${B}(${body})${A}`, "u");

/**
 * ⚠️ המלכודת הגדולה: "הייתי רוצה להזמין" / "היינו שמחים לשריין" הן בקשות
 * עתידיות, לא עדות לביקור. הן נפוצות מאוד אצלנו, ולכן נבדקות ראשונות.
 */
const REQUEST_TRAP = new RegExp(
  `(הייתי|היינו|הייתה|היתה|רציתי|רצינו)\\s+(רוצה|רוצים|רוצות|שמח|שמחה|שמחים|מעוניינ\\p{L}*|צריכ\\p{L}*|מבקש\\p{L}*|לשריין|להזמין)`,
  "u"
);

/** עדות חד משמעית לביקור שכבר קרה */
const VISIT_STRONG = rx(
  "ביקרנו|ביקרתי|אכלנו|אכלתי|ישבנו|ישבתי|סעדנו|טעמנו|חגגנו|חגגתי|בילינו|ביליתי|" +
    "באנו|באתי|הגענו|הגעתי|יצאנו מ|היינו אצלכם|הייתי אצלכם"
);

/** עדות חלשה ("היינו", "היה לנו") - נדרשת רק יחד עם עוגן של מקום או זמן */
const VISIT_WEAK = rx("היינו|הייתי|היה לנו|הייתה לנו|היתה לנו");
const VISIT_ANCHOR = rx(
  "אצלכם|אצלכן|אצלך|אצלכ|במקום|במסעדה|בבית הקפה|בקפה|אתמול|שלשום|אמש|" +
    "בשבת|בשישי|בחמישי|ברביעי|בשלישי|בשני|בראשון|בסופש|בסוףש|השבוע|שעבר|בערב|בצהריים|בבוקר"
);

/** שבח מפורש על החוויה. מכוון לצד הצר - מילה דו-משמעית לא נכנסת. */
const POSITIVE = rx(
  "כיף|נהנינו|נהניתי|נהנו|טעים|טעימה|טעימים|מושלם|מושלמת|מעולה|מעולים|מדהים|מדהימה|" +
    "מהמם|מהממת|תענוג|מפנק|מפנקת|נהדר|נהדרת|אהבנו|אהבתי|התאהבנו|ממליצ\\p{L}*|מומלץ|" +
    "אלופים|תותחים|שאפו|פצצה|מפרגנ\\p{L}*|חמים|חוויה"
);
const POSITIVE_PHRASE = /(כל הכבוד|יישר כוח|ברמה אחרת|היה טוב|היה כיף|היה מעולה|היה מושלם|היה טעים|היה מדהים|הכי טעים|אין על|אין מילים)/;

/**
 * כל אלה מבטלים. חלקם שליליים בבירור, וחלקם רק **מסייגים** - "אבל" אחרי שבח
 * הוא כמעט תמיד הסתייגות, ובמצב כזה בקשת ביקורת היא בדיוק הדבר הלא נכון.
 */
const NEGATIVE = new RegExp(
  // ⚠️ "נורא טעים" בעברית הוא שבח ולא תלונה, ולכן המילה נחשבת שלילית רק כשלא
  // באה אחריה מילה חיובית. בלי זה פרגון אמיתי היה נפסל.
  "גרוע|נורא(?!\\s*(טעים|כיף|נחמד|יפה|נעים|שווה|מוצלח))|מאכזב|אכזב|לא מרוצ|מקולקל|מגעיל|דוחה|שערורי|בושה|עלוב|יקר מדי|יקרים מדי|" +
    "איטי|קר מדי|לא טעים|לא נעים|לא שווה|לא מומלץ|לא אחזור|לא נחזור|לא אשוב|" +
    "תלונה|להתלונן|התלוננ|מתלונן|בעיה|בעייתי|פחות טוב|ממש לא|חבל ש|למרות|אבל|" +
    "מצטער|סליחה|נזק|החזר|לצערי|לצערנו"
);

/** הודעה שהיא בעצם בקשה או שאלה - לא רגע של פרגון */
const NOT_A_COMPLIMENT = /[?？]|להזמין|הזמנה|לשריין|לבטל|תפריט|כמה עולה|מחיר|שעות|פתוחים|חניה|כשר/;

export interface ReviewGateInput {
  /** ההודעה האחרונה של הלקוח */
  text: string;
  /** כל מה שהלקוח כתב בפרק הנוכחי - לאיתור תלונה מוקדמת יותר */
  episodeText?: string;
  /** כבר הוזמן להשאיר ביקורת (בפרק / בחודשים האחרונים) */
  alreadyInvited?: boolean;
  /** השיחה הוסלמה או מטופלת בידי נציג */
  escalated?: boolean;
}

/**
 * האם מותר להזמין את הלקוח להשאיר ביקורת. ברירת המחדל היא **לא**.
 */
export function shouldInviteReview(input: ReviewGateInput): boolean {
  const text = (input.text ?? "").trim();
  if (!text || input.alreadyInvited || input.escalated) return false;
  // הודעה ארוכה מדי כמעט תמיד מכילה גם משהו אחר (בקשה, הסתייגות, סיפור)
  if (text.length > 400) return false;

  if (NOT_A_COMPLIMENT.test(text)) return false;
  if (NEGATIVE.test(text)) return false;
  if (REQUEST_TRAP.test(text)) return false;
  // גם תלונה מוקדמת יותר באותו פרק פוסלת - אי אפשר לבקש ביקורת ממי שכעס לפני רגע
  if (input.episodeText && NEGATIVE.test(input.episodeText)) return false;

  const visited = VISIT_STRONG.test(text) || (VISIT_WEAK.test(text) && VISIT_ANCHOR.test(text));
  if (!visited) return false;

  return POSITIVE.test(text) || POSITIVE_PHRASE.test(text);
}

/**
 * נוסחי ההזמנה. מנוסחים כתוספת לתשובה החמה שכבר נאמרה, ולא כהודעה בפני עצמה,
 * ולכן הם לא חוזרים על התודה. מגוונים כדי שלא ייראו כמו אוטומט.
 */
export const REVIEW_INVITE_VARIANTS = [
  "אם יש לכם דקה, ביקורת קצרה בגוגל עוזרת לנו המון 🤍",
  "ואם בא לכם לשתף אחרים בחוויה, זה הקישור להשאיר ביקורת 🤍",
  "ואם תרצו לעשות לנו טוב על הלב - ביקורת קטנה בגוגל 🤍",
];

/** שורת ההזמנה המלאה, מוכנה לצירוף לסוף התשובה. */
export function reviewInviteLine(url: string, pick = Math.random()): string {
  const i = Math.min(REVIEW_INVITE_VARIANTS.length - 1, Math.floor(pick * REVIEW_INVITE_VARIANTS.length));
  return `${REVIEW_INVITE_VARIANTS[i]}\n${url}`;
}
