import type { Reservation } from "./types";

/** תבניות ההודעה שנשלחות ללקוח על בקשת הזמנה - משותפות לעמוד ההזמנות
 *  ולכרטיס ההזמנה שבתוך שיחת התיבה (16.9). ניתנות לעריכה לפני שליחה.
 *  הנוסחים נכתבו על ידי בעל העסק (18.9).
 *
 *  ⚠️ הדגשה בכוכבית **בודדת** - זה מה שוואטסאפ מרנדר כמודגש (כוכבית כפולה
 *  מוצגת כתווים גולמיים). ולעולם לא עוטפים מספר טלפון בכוכביות: *8149 מתחיל
 *  בכוכבית, ועטיפה שלו שוברת את הסימון.
 *
 *  חשוב (הוחלט 20.8, עדיין בתוקף): "יש מקום" איננו אישור סופי - ההזמנה נסגרת
 *  רק אחרי תשלום פיקדון 100 ש"ח בקישור שהצוות שולח. */

const WEEKDAYS = ["ראשון", "שני", "שלישי", "רביעי", "חמישי", "שישי", "שבת"];

/** התאריך בתבנית: קנוני מ-dateISO ("יום חמישי, 13.8") כשקיים, אחרת מילות הלקוח. */
export function templateDate(r: Reservation): string {
  if (r.dateISO && /^\d{4}-\d{2}-\d{2}$/.test(r.dateISO)) {
    const [y, m, d] = r.dateISO.split("-").map(Number);
    return `יום ${WEEKDAYS[new Date(Date.UTC(y, m - 1, d)).getUTCDay()]}, ${d}.${m}`;
  }
  return r.dateText;
}

export function approveTemplate(r: Reservation): string {
  return (
    `חדשות טובות! 😊 יש מקום!\n\n` +
    `הצוות אישר את ההזמנה ל*${templateDate(r)} בשעה ${r.time}*, ל-*${r.people} סועדים* על שם *${r.name}*.\n\n` +
    `כדי לאשר את ההזמנה סופית, נשלח אליך עכשיו קישור לתשלום פיקדון בסך *100 ש״ח*. ברגע שהתשלום יבוצע, השולחן יישמר עבורכם.\n\n` +
    `מחכים לכם בקפה קוואלי 🥂`
  );
}

export function declineTemplate(r: Reservation): string {
  return (
    `היי *${r.name}* 🙏\n` +
    `בדקנו מול הצוות, ולצערנו אין לנו מקום פנוי ל-*${templateDate(r)} בשעה ${r.time}*.\n\n` +
    `רוצה שנבדוק לך *יום או שעה אחרים*? 😊\n` +
    `אפשר גם לחייג אלינו ב-*8149 או 050-979-8917, ונשמח לעזור למצוא פתרון.\n\n` +
    `מקווים לראות אתכם בקפה קוואלי ❤️`
  );
}

export function cancelTemplate(r: Reservation): string {
  return `היי ${r.name} 🙏 ההזמנה שלך ל-${templateDate(r)} בשעה ${r.time} (${r.people} אנשים) בוטלה. אם מדובר בטעות או שתרצה לקבוע מחדש, אפשר לחייג *8149 או 050-979-8917 ונשמח לעזור.`;
}
