  "ראיתי את המקום שלכם באינסטגרם נראה מהמם איפה אתם נמצאים?",
  "למה מוזמן? אני נקבה...מה השעות פעילות שלכם? אתם כשרים? ספר לי על המקום",
  "מגניב...עם מי מומלץ לבוא? לדייט עם בעלי או שזה יותר מותאם למשפחות וזה? מה האווירה שם",
  "מה הכוונה גינת ילדים? גן שעשועים כאילו?",
  "וואו איזה יופי..בעלי מתנייד בכיסא גלגלים יש חניית נכים?",
  "מה טווח המחירים? נחשב יקר או סביר יחסית? כי המקום נראה יוקרתי בטירוף ממה שראיתי באינסטגרם",
  "כן מעניין אותי על מה אתה ממליץ",
  "אנחנו פחות בעניין של דגים האמת..חשבנו שזאת מסעדה איטלקית..",
  "תרכיב לנו המלצה לדייט כולל קינוח בסוף ותגיד לי גם כמה יוצא עם 10% טיפ",
  "מה עם איזה סלט?",
  "430 שקל לבית קפה...אתה באמת חושב שזה שווה את הכסף?",
  "בוא ננסה משהו יותר צנוע אבל שלא נצא משם רעבים",
  "מה קשור אמריקנו חח? רוצים איזה כוס יין",
  "אוקיי נשמע יותר טוב..אני אזמין מקום ליום חמישי..צריך להשאיר אשראי או משהו לשמירת מקום או שפשוט שומרים?",
