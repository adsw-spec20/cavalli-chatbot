let cid;
const clientId = "replay-cost-" + Date.now();
for (const m of msgs) {
  const r = await (await fetch(B + "/api/chat", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ message: m, conversationId: cid, clientId }),
  })).json();
  cid = r.conversationId;
}
console.log("replay done, turns=" + msgs.length);
