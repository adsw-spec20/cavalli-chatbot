async function send(text, conversationId, clientId) {
  const r = await fetch(B + "/api/chat", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ message: text, conversationId, clientId }),
  });
  return r.json();
}

